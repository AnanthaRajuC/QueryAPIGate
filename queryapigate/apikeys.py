def _row_to_role(row):
    entry = json.loads(row['details_json'])
    entry['created_at'] = row['created_at']
    return entry


def _read_roles():
    rows = db.connection().execute('SELECT name, created_at, details_json FROM roles').fetchall()
    return {row['name']: _row_to_role(row) for row in rows}


def _upsert_role(conn, name, entry):
    details = {k: v for k, v in entry.items() if k != 'created_at'}
    conn.execute("""
        INSERT INTO roles (name, created_at, details_json) VALUES (?, ?, ?)
        ON CONFLICT(name) DO UPDATE SET created_at = excluded.created_at, details_json = excluded.details_json
    """, (name, entry.get('created_at') or store.now(), json.dumps(details)))


def _get_role_or_404(name):
    row = db.connection().execute('SELECT name, created_at, details_json FROM roles WHERE name = ?',
                                  (name,)).fetchone()
    if row is None:
        raise ApiError(f"Role '{name}' not found", 404)
    return _row_to_role(row)


def list_roles():
    return {name: {'collections': [], **entry} for name, entry in _read_roles().items()}


def create_role(name, connections=None, allow_writes=False, queries=None, rate_limit=None, allowed_ips=None,
                allowed_write_ops=None, collections=None, example=False, allowed_tables=None):
    if not isinstance(name, str) or not _NAME_RE.match(name):
        raise ApiError("Role name may only contain letters, digits, spaces, '.', '_' and '-'")
    collections = _normalize_collections(collections)
    _require_existing_collections(collections)
    with db.transaction() as conn:
        if conn.execute('SELECT 1 FROM roles WHERE name = ?', (name,)).fetchone() is not None:
            raise ApiError(f"A role named '{name}' already exists")
        entry = {
            'connections': _normalize_connections(connections),
            'allow_writes': bool(allow_writes),
            'queries': _normalize_queries(queries),
            'collections': collections,
            'rate_limit': _validate_rate_limit(rate_limit),
            'allowed_ips': _validate_allowed_ips(allowed_ips),
            'allowed_write_ops': _validate_allowed_write_ops(allowed_write_ops),
            'allowed_tables': _validate_allowed_tables(allowed_tables),
            'created_at': store.now(),
            **({'example': True} if example else {}),  # installed by `examples load` - see examples.py
        }
        _upsert_role(conn, name, entry)



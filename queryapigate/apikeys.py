def collection_grants():
    """{collection: {'keys': [names], 'roles': [names]}} for every collection any key or role is granted -
    including one with no queries left, so a grant that has gone inert shows up instead of hiding."""
    granted = {}
    for kind, entries in (('keys', _read()), ('roles', _read_roles())):
        for entry_name, entry in entries.items():
            for collection in entry.get('collections', []):
                granted.setdefault(collection, {'keys': [], 'roles': []})[kind].append(entry_name)
    for value in granted.values():
        value['keys'].sort()
        value['roles'].sort()
    return granted


def rewrite_collection_grants(old, new, drop_old):
    """Add ``new`` beside ``old`` on every key and role that has ``old`` (and, with ``drop_old``, remove ``old``).
    Rename does this twice - widen first, narrow last - so at no instant does a grant lose reach it should
    keep. Returns (keys changed, roles changed). Written directly rather than through update_key(): a rename
    is not a new grant, so the "must already exist" check does not apply."""
    changed = {}
    with db.transaction() as conn:
        for kind, read, upsert in (('keys', _read, _upsert), ('roles', _read_roles, _upsert_role)):
            entries = read()
            touched = []
            for entry_name, entry in entries.items():
                current = entry.get('collections', [])
                if old not in current:
                    continue
                updated = set(current) | {new}
                if drop_old:
                    updated.discard(old)
                updated = sorted(updated)
                if updated != current:
                    entry['collections'] = updated
                    upsert(conn, entry_name, entry)
                    touched.append(entry_name)
            changed[kind] = sorted(touched)
    return changed['keys'], changed['roles']


def _parsed_rate_limit(entry):
    """The stored rate_limit string, parsed to (count, period) once here rather than re-parsed by every
    caller - or None, for no per-key limit (unset) or a malformed stored value, which should not itself
    break authentication any more than a malformed expires_at should (see is_expired())."""
    raw = entry.get('rate_limit')
    if not raw:
        return None
    try:
        return config.parse_rate_limit(raw, label='rate_limit')
    except ValueError:
        return None


def authenticate(supplied, client_ip=None):
    """Resolve the ``X-API-Key`` header value to a Permission, or None if it matches no key at all (wrong
    secret, or a right one that's inactive, expired, or used from outside its allowed_ips - all three fail
    the same way as a plain wrong key, not a distinct error, so a caller learns nothing about *why* a
    supplied key didn't work). ``client_ip`` is only used to check a scoped key's own allowed_ips
    restriction, if it has one; the admin key is never restricted by it."""
    if not supplied:
        return None
    expected = config.api_key()
    if expected and hmac.compare_digest(supplied.encode('utf-8', 'replace'), expected.encode('utf-8')):
        return Permission(name='admin', admin=True, connections=ALL_CONNECTIONS, allow_writes=True,
                          queries=ALL_QUERIES, rate_limit=None, allowed_write_ops=None)
    supplied_hash = _hash(supplied)
    # One indexed lookup (api_keys.hash is UNIQUE) instead of loading and scanning every key - a full scan
    # made each request's cost grow linearly with the number of keys. Matching on the hash rather than the
    # secret means the lookup's own timing can only ever reveal something about a SHA-256 digest, which is
    # useless for guessing a secret; compare_digest() below stays as a belt-and-braces final check.
    rows = db.connection().execute(
        'SELECT name, hash, active, expires_at, created_at, details_json FROM api_keys WHERE hash = ?',
        (supplied_hash,)).fetchall()
    for row in rows:
        name, entry = row['name'], _row_to_entry(row)
        if entry.get('active', True) and not is_expired(entry) and _ip_allowed(entry, client_ip) \
                and hmac.compare_digest(supplied_hash, entry['hash']):
            _record_use(name)
            connections = entry['connections']
            queries = entry.get('queries', [])  # absent on a key stored before this field existed
            return Permission(name=name, admin=False,
                              connections=connections if connections == ALL_CONNECTIONS else frozenset(connections),
                              allow_writes=bool(entry.get('allow_writes', False)),
                              queries=queries if queries == ALL_QUERIES else _queries_map(queries),
                              rate_limit=_parsed_rate_limit(entry),
                              allowed_write_ops=entry.get('allowed_write_ops'),
                              collections=frozenset(entry.get('collections', [])),
                              allowed_tables=frozenset(entry['allowed_tables'])
                              if entry.get('allowed_tables') is not None else None)
    return None


def import_legacy_keys_if_empty():
    """First-boot bootstrap for api_keys.json, the same shape as store.py's own
    import_legacy_connections_if_empty(): only runs while api_keys is completely empty, reads the legacy
    file directly, and never touches or deletes it afterward. Skipped on Postgres - see
    store.import_legacy_data_if_empty()."""
    if db.is_postgres() or db.connection().execute('SELECT 1 FROM api_keys LIMIT 1').fetchone() is not None:
        return
    try:
        with open(config.api_keys_file(), 'r') as f:
            keys = json.load(f).get('keys', {})
    except (FileNotFoundError, json.JSONDecodeError):
        return
    with db.transaction() as conn:
        for name, entry in keys.items():
            if isinstance(entry, dict) and entry.get('hash'):
                _upsert(conn, name, entry)


def import_legacy_roles_if_empty():
    """Same bootstrap shape as import_legacy_keys_if_empty(), for roles.json/roles."""
    if db.is_postgres() or db.connection().execute('SELECT 1 FROM roles LIMIT 1').fetchone() is not None:
        return
    try:
        with open(config.roles_file(), 'r') as f:
            roles = json.load(f).get('roles', {})
    except (FileNotFoundError, json.JSONDecodeError):
        return
    with db.transaction() as conn:
        for name, entry in roles.items():
            if isinstance(entry, dict):
                _upsert_role(conn, name, entry)

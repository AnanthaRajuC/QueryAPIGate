# What Kubernetes sets for a Service named like a setting (service links): QUERYAPIGATE_SERVICE_HOST,
# QUERYAPIGATE_EVENTS_PORT_5002_TCP_ADDR... - never anyone's typo.
_SERVICE_LINK = re.compile(r'_(SERVICE_HOST|SERVICE_PORT(_[A-Z0-9_]+)?|PORT_[0-9]+_(TCP|UDP|SCTP)(_[A-Z]+)?)$')


def unknown(environ, secret_settings):
    """The set QUERYAPIGATE_* names that are no setting, sorted."""
    files = {f'{name}_FILE' for name in secret_settings}
    return sorted(name for name in environ if name.startswith('QUERYAPIGATE_') and name not in KNOWN
                  and name not in files and not _SERVICE_LINK.search(name) and not name.startswith(_TESTS))


_TESTS = ('QUERYAPIGATE_TEST_', 'QUERYAPIGATE_IT_', 'QUERYAPIGATE_DATAPLANE_TEST_')  # the test suite's own

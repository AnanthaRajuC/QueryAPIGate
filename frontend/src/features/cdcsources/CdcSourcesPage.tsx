import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useState, type FormEvent, type ReactNode } from 'react';

import { api, unwrap, unwrapEmpty, unwrapWithEtag, type Schemas } from '@/api/client';
import { useCan, useConnections, useSettings } from '@/app/data';
import { Field, FormActions, Loading, copyText, useFeedback } from '@/app/feedback';
import { ExperimentalTag } from '@/components/Experimental';
import { PencilIcon, TrashIcon } from '@/components/icons';
import { Time } from '@/components/Time';
import { useReport } from '@/features/exports/shared';

import { sinkProperties, useCdcSources } from './shared';

// CDC sources (ADR 0033 §11), on /api/v1/cdc-sources: the Debezium Servers that tell live queries what changed. Each
// one's secret is generated by the server and shown once - on creating it, or rotating it - with the sink lines to
// paste into Debezium Server's application.properties.

type CdcSource = Schemas['CdcSource'];

const GRACE_CHOICES: [string, string][] = [
  ['60', 'for 1 hour'],
  ['1440', 'for 1 day'],
  ['10080', 'for 1 week'],
  ['0', 'not at all - it stops now'],
];

function Status({ source }: { source: CdcSource }) {
  if (source.managed_by) return <span className="dim">from {source.managed_by}</span>;
  return (
    <>
      {source.last_received_at ? (
        <>
          last post <Time value={source.last_received_at} />
        </>
      ) : (
        <span className="dim">never reached</span>
      )}
      {source.previous_expires_at && (
        <div className="hint">
          old secret works until <Time value={source.previous_expires_at} />
        </div>
      )}
    </>
  );
}

export function CdcSourcesPage() {
  const list = useCdcSources();
  const can = useCan();
  const { openDrawer, toast } = useFeedback();
  const report = useReport();
  const client = useQueryClient();
  const write = can('connections.write');
  const newSource = () => openDrawer({ title: 'New CDC source', content: <SourceForm /> });

  const remove = async (name: string) => {
    if (
      !window.confirm(
        `Delete CDC source '${name}'? Its Debezium Server's posts are refused from now on, and live queries stop hearing of its changes.`,
      )
    )
      return;
    try {
      unwrapEmpty(await api.DELETE('/api/v1/cdc-sources/{name}', { params: { path: { name } } }));
      toast('Deleted ' + name);
      void client.invalidateQueries({ queryKey: ['cdc-sources'] });
    } catch (error) {
      report(error);
    }
  };

  let body: ReactNode;
  if (list.isPending) {
    body = <Loading text="Loading CDC sources…" />;
  } else if (list.isError) {
    body = <div className="hint">{list.error.message}</div>;
  } else if (!list.data.length) {
    body = (
      <div className="empty">
        <strong>No CDC sources yet</strong>
        <span>
          A CDC source is a Debezium Server reading a database&apos;s change log and telling QueryAPIGate
          which tables changed - never the rows. Live queries reading those tables send their new result, and
          cached responses for them are refreshed.
        </span>
        {write && (
          <button type="button" className="btn primary" onClick={newSource}>
            New CDC source
          </button>
        )}
      </div>
    );
  } else {
    body = (
      <div style={{ overflowX: 'auto' }}>
        <table className="grid">
          <thead>
            <tr>
              {['Name', 'Connection', 'Server', 'Posts to', 'Status', ''].map((t, i) => (
                <th key={i}>{t}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {list.data.map((s) => (
              <tr key={s.name} data-name={s.name}>
                <td>
                  <span className="name">{s.name}</span>
                </td>
                <td>{s.connection}</td>
                <td className="dim">{s.server_name ?? 'any'}</td>
                <td className="mono">{s.ingest_path}</td>
                <td>
                  <Status source={s} />
                </td>
                <td>
                  <div className="actions" hidden={!write || Boolean(s.managed_by)}>
                    <button
                      type="button"
                      className="btn ghost sm"
                      onClick={() =>
                        openDrawer({
                          title: 'Rotate secret',
                          kicker: s.name,
                          content: <RotateForm source={s} />,
                        })
                      }
                    >
                      Rotate
                    </button>
                    <button
                      type="button"
                      className="btn ghost sm icon"
                      title={`Edit ${s.name}`}
                      aria-label="Edit"
                      onClick={() =>
                        openDrawer({
                          title: 'Edit CDC source',
                          kicker: s.name,
                          content: <SourceForm name={s.name} />,
                        })
                      }
                    >
                      <PencilIcon />
                    </button>
                    <button
                      type="button"
                      className="btn ghost sm icon danger"
                      title={`Delete ${s.name}`}
                      aria-label="Delete"
                      onClick={() => void remove(s.name)}
                    >
                      <TrashIcon />
                    </button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );
  }

  return (
    <>
      <div className="page-head">
        <div className="titles">
          <h1>
            CDC sources <ExperimentalTag />
          </h1>
          <span className="sub">
            Debezium Servers that tell live queries, and the response cache, which tables changed.
          </span>
        </div>
        <span className="spacer" />
        {write && (
          <button id="new-cdc-source" type="button" className="btn primary" onClick={newSource}>
            New CDC source
          </button>
        )}
      </div>
      <LiveQueriesOff />
      <div id="cdc-sources-table" className="panel">
        {body}
      </div>
    </>
  );
}

/** Sources can be set up while live queries are off, but nothing is taken from them until they're on - say so, to
 * whoever may read the settings. */
function LiveQueriesOff() {
  const can = useCan();
  const settings = useSettings();
  if (!can('settings.read') || !settings.data) return null;
  const row = settings.data
    .flatMap((section) => section.rows)
    .find((r) => r.env === 'QUERYAPIGATE_LIVE_QUERIES');
  if (!row || row.value !== 'off') return null;
  return (
    <div className="panel hint" id="live-queries-off" style={{ padding: '10px 14px' }}>
      Live queries are off: until <code>QUERYAPIGATE_LIVE_QUERIES</code> is on, posts from these sources are
      refused (404) and Debezium keeps retrying them.
    </div>
  );
}

function SourceForm({ name }: { name?: string }) {
  const detail = useQuery({
    queryKey: ['cdc-sources', 'detail', name],
    queryFn: async () =>
      unwrapWithEtag(await api.GET('/api/v1/cdc-sources/{name}', { params: { path: { name: name! } } })),
    enabled: Boolean(name),
    retry: false,
    gcTime: 0,
  });
  if (name && detail.isPending) return <Loading />;
  if (name && detail.isError) return <div className="hint">{detail.error.message}</div>;
  return (
    <SourceFields
      key={name ?? ''}
      name={name}
      existing={detail.data?.data}
      etag={detail.data?.etag ?? null}
    />
  );
}

function SourceFields({
  name,
  existing,
  etag,
}: {
  name?: string;
  existing?: CdcSource;
  etag: string | null;
}) {
  const isEdit = Boolean(name);
  const { closeDrawer, openDrawer, showError, toast } = useFeedback();
  const report = useReport();
  const client = useQueryClient();
  const connections = useConnections();
  const [sourceName, setSourceName] = useState(name ?? '');
  const [connection, setConnection] = useState(existing?.connection ?? '');
  const [serverName, setServerName] = useState(existing?.server_name ?? '');

  const save = useMutation({
    mutationFn: async () => {
      if (isEdit) {
        return unwrap(
          await api.PATCH('/api/v1/cdc-sources/{name}', {
            params: { path: { name: name! }, header: etag ? { 'If-Match': etag } : {} },
            body: { connection, server_name: serverName.trim() || null },
          }),
        );
      }
      return unwrap(
        await api.POST('/api/v1/cdc-sources', {
          body: {
            name: sourceName.trim(),
            connection,
            ...(serverName.trim() ? { server_name: serverName.trim() } : {}),
          },
        }),
      );
    },
    onSuccess: (saved) => {
      showError('');
      void client.invalidateQueries({ queryKey: ['cdc-sources'] });
      if (!isEdit) {
        const created = saved as Schemas['CdcSourceWithSecret'];
        openDrawer({
          title: 'CDC source created',
          kicker: created.name,
          wide: true,
          content: <SecretAndSink secret={created.secret} ingestPath={created.ingest_path} />,
        });
      } else {
        closeDrawer();
        toast('Updated ' + saved.name);
      }
    },
    onError: report,
  });

  const submit = (e: FormEvent) => {
    e.preventDefault();
    if (!isEdit && !sourceName.trim()) {
      showError('A name is required.', { errors: { name: 'This field is required' } });
      return;
    }
    if (!connection) {
      showError('Choose the connection whose changes it reports.', {
        errors: { connection: 'This field is required' },
      });
      return;
    }
    save.mutate();
  };

  return (
    <form className="form" noValidate onSubmit={submit}>
      <Field
        id="c-name"
        label="Name"
        hint={isEdit ? undefined : 'Part of the address Debezium posts to, e.g. rental.'}
      >
        <input
          id="c-name"
          value={sourceName}
          placeholder="rental"
          autoComplete="off"
          spellCheck={false}
          disabled={isEdit}
          autoFocus={!isEdit}
          onChange={(e) => setSourceName(e.target.value)}
        />
      </Field>
      <Field
        id="c-connection"
        label="Connection"
        hint="The database Debezium reads. Live queries on this connection listen for its changes."
      >
        <select id="c-connection" value={connection} onChange={(e) => setConnection(e.target.value)}>
          <option value="">Choose…</option>
          {(connections.data ?? []).map((c) => (
            <option key={c.name} value={c.name}>
              {c.name}
            </option>
          ))}
        </select>
      </Field>
      <Field
        id="c-server"
        label="Server name"
        hint="Optional: Debezium's topic.prefix. A post from any other server is then refused."
      >
        <input
          id="c-server"
          value={serverName}
          placeholder="rental"
          autoComplete="off"
          spellCheck={false}
          onChange={(e) => setServerName(e.target.value)}
        />
      </Field>
      {!isEdit && (
        <div className="hint">
          The signing secret is generated when you create it, and shown once - with the lines to paste into
          Debezium Server.
        </div>
      )}
      <FormActions onCancel={closeDrawer}>
        <button type="submit" className="btn primary" disabled={save.isPending}>
          {isEdit ? 'Save' : 'Create'}
        </button>
      </FormActions>
    </form>
  );
}

function RotateForm({ source }: { source: CdcSource }) {
  const { closeDrawer, openDrawer, toast } = useFeedback();
  const report = useReport();
  const client = useQueryClient();
  const [grace, setGrace] = useState('60');
  const path = { params: { path: { name: source.name } } };
  const rotate = useMutation({
    mutationFn: async () =>
      unwrap(
        await api.POST('/api/v1/cdc-sources/{name}/rotate', {
          ...path,
          body: { grace_minutes: Number(grace) },
        }),
      ),
    onSuccess: (rotated) => {
      void client.invalidateQueries({ queryKey: ['cdc-sources'] });
      openDrawer({
        title: 'Secret rotated',
        kicker: rotated.name,
        wide: true,
        content: (
          <SecretAndSink
            secret={rotated.secret}
            ingestPath={rotated.ingest_path}
            hint={
              rotated.previous_expires_at ? (
                <>
                  Store this now - it cannot be shown again. The old secret keeps working until{' '}
                  <Time value={rotated.previous_expires_at} />: restart Debezium Server with the new one
                  before then.
                </>
              ) : (
                'Store this now - it cannot be shown again. The old secret has stopped working.'
              )
            }
          />
        ),
      });
    },
    onError: report,
  });
  const end = useMutation({
    mutationFn: async () => unwrap(await api.DELETE('/api/v1/cdc-sources/{name}/previous', path)),
    onSuccess: () => {
      void client.invalidateQueries({ queryKey: ['cdc-sources'] });
      closeDrawer();
      toast('The old secret of ' + source.name + ' stopped working');
    },
    onError: report,
  });

  if (source.previous_expires_at) {
    return (
      <div className="form">
        <Field
          label="Secret"
          hint="Rotated: posts signed with the new secret or the old one are both accepted until then."
        >
          <div className="key-secret" id="c-previous">
            <span>
              The old secret works until <Time value={source.previous_expires_at} />
            </span>
            <button
              type="button"
              className="btn sm danger"
              disabled={end.isPending}
              onClick={() => {
                if (
                  window.confirm(
                    `Stop the old secret of '${source.name}' now? Posts signed with it are refused.`,
                  )
                )
                  end.mutate();
              }}
            >
              End now
            </button>
          </div>
        </Field>
      </div>
    );
  }
  return (
    <div className="form">
      <Field
        id="c-grace"
        label="Keep the old secret working"
        hint="A new secret, shown once. Restart Debezium Server with it while the old one still works."
      >
        <select id="c-grace" value={grace} onChange={(e) => setGrace(e.target.value)}>
          {GRACE_CHOICES.map(([value, label]) => (
            <option key={value} value={value}>
              {label}
            </option>
          ))}
        </select>
      </Field>
      <FormActions onCancel={closeDrawer}>
        <button
          type="button"
          className="btn primary"
          disabled={rotate.isPending}
          onClick={() => rotate.mutate()}
        >
          Rotate secret
        </button>
      </FormActions>
    </div>
  );
}

/** The secret, shown this once, and Debezium Server's sink lines - the secret passed as WEBHOOK_SECRET. */
function SecretAndSink({
  secret,
  ingestPath,
  hint,
}: {
  secret: string;
  ingestPath: string;
  hint?: ReactNode;
}) {
  const { closeDrawer, toast } = useFeedback();
  const sink = sinkProperties(ingestPath);
  return (
    <div className="form">
      <div className="field">
        <label htmlFor="c-secret">Signing secret</label>
        <input
          id="c-secret"
          readOnly
          className="mono"
          value={secret}
          onClick={(e) => e.currentTarget.select()}
        />
        <div className="hint">
          {hint ??
            'Store this now - it cannot be shown again. To change it later, rotate it. Give it to Debezium Server as the WEBHOOK_SECRET environment variable.'}
        </div>
      </div>
      <div className="field">
        <label htmlFor="c-sink">Debezium Server&apos;s application.properties: the sink</label>
        <pre className="curlbox" id="c-sink">
          {sink}
        </pre>
        <div className="hint">
          Use the address Debezium Server reaches QueryAPIGate at, if it isn&apos;t this one. The source lines
          (connector, database, tables) depend on the database - see the API documentation&apos;s Live queries
          section.
        </div>
      </div>
      <div className="form-actions">
        <button type="button" className="btn ghost" onClick={() => copyText(secret, toast)}>
          Copy secret
        </button>
        <button type="button" className="btn ghost" onClick={() => copyText(sink, toast)}>
          Copy sink lines
        </button>
        <button type="button" className="btn primary" onClick={closeDrawer}>
          Done
        </button>
      </div>
    </div>
  );
}
